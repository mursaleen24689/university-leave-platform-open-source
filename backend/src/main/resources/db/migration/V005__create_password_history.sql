-- Password history: the last five hashes per account block reuse.
-- Only hashes are stored, never the password itself.

CREATE TABLE password_history (
    id            NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    user_id       NUMBER(19)         NOT NULL,
    password_hash VARCHAR2(100 CHAR) NOT NULL,
    changed_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_password_history PRIMARY KEY (id),
    CONSTRAINT fk_password_history_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE INDEX idx_password_history_user ON password_history (user_id, changed_at);

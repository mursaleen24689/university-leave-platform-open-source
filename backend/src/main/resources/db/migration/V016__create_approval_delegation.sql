-- Dated delegated approvers (docs/REQUIREMENTS.md, "a supervisor or a head of
-- department can hand their approving to a named colleague for a period").
-- Oracle Database Free 26ai, unquoted identifiers.
--
-- One row is one person handing one kind of approving to one named colleague for
-- a dated window. A head of department going on leave themselves, or a supervisor
-- seconded elsewhere, otherwise leaves requests sitting unread in a queue nobody
-- is standing at - the same failure the earlier application solved by whoever happened to know the
-- admin password logging in as them, which leaves the audit trail naming the
-- wrong person. Here the delegatee acts as themself: the request still shows the
-- name of the person who recommended or decided it, and the audit note adds that
-- they were acting for the delegator.
--
-- WHY A SCOPE COLUMN. Approving happens at two different steps with two
-- different authorities, and a person can hold one without the other:
--   SUPERVISOR - the name stored on a pending request as it was recommended.
--     Only someone with direct reports can hand this out, because only someone
--     with direct reports has requests of that kind sent to them.
--   DECISION   - the final approve/refuse a head of department makes for their
--     department. Only an acting head can hand this out, and the department is
--     snapshotted below: the delegation covers that department's decisions as
--     they stood when the window was written, so a later transfer does not
--     silently move the authority with the person.
-- A central administrator's university-wide authority is deliberately NOT
-- delegable: it is the fallback for the whole platform, including the screens
-- that manage these very rows, and handing it to a colleague for a fortnight is
-- a bigger act than handing over one department's leave decisions.
--
-- WHY DATES RATHER THAN AN ACTIVE FLAG ALONE. The point of the feature is that
-- somebody is away for a known period. A window with an end date closes itself
-- with nobody having to remember to open the screen afterwards; a delegation
-- revoked early keeps its row, marked, so the record of who could act during
-- the window survives. "Revoked" and "not revoked" are therefore the whole
-- meaning of ACTIVE - an ended window keeps its flag and is excluded by its
-- end_date - and queries for the usable set ask for ACTIVE = 1 AND the window
-- covers today, so expiry is a comparison, not a scheduled job.
--
-- Two live windows for the same person and step would put one queue in two
-- pairs of hands, so the service refuses the second. It is not a database
-- constraint, and that is deliberate: a window that ended last month keeps
-- ACTIVE = 1 - nobody revoked it - so a keyed unique index over the live rows
-- would reject the fresh window for this year, which is the ordinary thing a
-- head of department does annually. The race the constraint would have closed
-- is closed instead the way approvals are protected elsewhere: creating a
-- window takes a pessimistic lock on the delegator's staff row first, so two
-- creations for one person are checked one after the other.

CREATE TABLE approval_delegation (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    reference         VARCHAR2(20 CHAR)   NOT NULL,
    from_employee_id  NUMBER(19)          NOT NULL,
    to_employee_id    NUMBER(19)          NOT NULL,
    scope             VARCHAR2(20 CHAR)   NOT NULL,
    department_id     NUMBER(19)          NULL,
    start_date        DATE                NOT NULL,
    end_date          DATE                NOT NULL,
    reason            VARCHAR2(1000 CHAR) NULL,
    active            NUMBER(1)           DEFAULT 1 NOT NULL,
    revoked_by_employee_id NUMBER(19)     NULL,
    revoked_at        TIMESTAMP WITH TIME ZONE NULL,
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_approval_delegation PRIMARY KEY (id),
    CONSTRAINT uq_delegation_reference UNIQUE (reference),
    CONSTRAINT fk_delegation_from FOREIGN KEY (from_employee_id)
        REFERENCES employee (id),
    CONSTRAINT fk_delegation_to FOREIGN KEY (to_employee_id)
        REFERENCES employee (id),
    CONSTRAINT fk_delegation_department FOREIGN KEY (department_id)
        REFERENCES department (id),
    CONSTRAINT fk_delegation_revoked_by FOREIGN KEY (revoked_by_employee_id)
        REFERENCES employee (id),
    CONSTRAINT ck_delegation_scope CHECK
        (scope IN ('SUPERVISOR', 'DECISION')),
    CONSTRAINT ck_delegation_distinct CHECK (from_employee_id <> to_employee_id),
    CONSTRAINT ck_delegation_dates CHECK (end_date >= start_date),
    -- A DECISION delegation is meaningless without the department it covers; a
    -- SUPERVISOR one names no department because the requests reach it by the
    -- supervisor's own name, whoever that person's employer department is.
    CONSTRAINT ck_delegation_department CHECK
        ((scope = 'DECISION' AND department_id IS NOT NULL)
         OR (scope = 'SUPERVISOR' AND department_id IS NULL)),
    CONSTRAINT ck_delegation_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_delegation_revocation CHECK
        ((active = 1 AND revoked_at IS NULL AND revoked_by_employee_id IS NULL)
         OR (active = 0 AND revoked_at IS NOT NULL
             AND revoked_by_employee_id IS NOT NULL))
);

COMMENT ON TABLE approval_delegation IS 'One person handing one approving step to a named colleague for a dated window';
COMMENT ON COLUMN approval_delegation.reference IS 'The number both sides quote, for example DL-000007; written by delegation_reference_bi';
COMMENT ON COLUMN approval_delegation.from_employee_id IS 'The supervisor or head of department whose approving this hands over';
COMMENT ON COLUMN approval_delegation.to_employee_id IS 'The colleague who may act during the window; never the same person as from_employee_id';
COMMENT ON COLUMN approval_delegation.scope IS 'SUPERVISOR hands over recommending; DECISION hands over the final decision of a department';
COMMENT ON COLUMN approval_delegation.department_id IS 'For DECISION: the department whose decisions are covered, snapshotted when the window is written; always NULL for SUPERVISOR';
COMMENT ON COLUMN approval_delegation.start_date IS 'First day the delegatee may act';
COMMENT ON COLUMN approval_delegation.end_date IS 'Last day the delegatee may act; the window closes after it with nobody having to remember';
COMMENT ON COLUMN approval_delegation.reason IS 'Why the handover is needed, in the delegator''s words; read by the delegatee and by anyone auditing the decision';
COMMENT ON COLUMN approval_delegation.active IS '1 while the row can be used; 0 once revoked or written off. An ended window keeps 1 and is excluded by its end_date';
COMMENT ON COLUMN approval_delegation.revoked_by_employee_id IS 'Who closed the window early; NULL while it is live';
COMMENT ON COLUMN approval_delegation.revoked_at IS 'When the window was closed early; NULL while it is live';

CREATE INDEX idx_delegation_from ON approval_delegation (from_employee_id, start_date);
CREATE INDEX idx_delegation_to ON approval_delegation (to_employee_id, active, end_date);

-- Same rule as tickets and profile requests, docs/DECISIONS.md ADR-016: the
-- database writes the quoted number from the id, because Oracle assigns the
-- identity value before a BEFORE INSERT row trigger runs and the INSERT
-- statement itself cannot see it.
CREATE OR REPLACE TRIGGER delegation_reference_bi
BEFORE INSERT ON approval_delegation
FOR EACH ROW
BEGIN
    :NEW.reference := 'DL-' || LPAD(TO_CHAR(:NEW.id), 6, '0');
END;
/

COMMENT ON COLUMN approval_delegation.reference IS 'Written by delegation_reference_bi from the id, in the form DL-000007; never typed and never edited';

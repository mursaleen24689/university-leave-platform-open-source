-- Casual leave, the first leave module (see docs/LEAVE-RULES.md).
-- Oracle Database Free 23ai, unquoted identifiers, single-row INSERTs.
--
-- Differences from the the earlier application tables this replaces: the balance stores allocated
-- and used only (remaining is derived), the leave type is a row rather than a
-- hard-coded string, and the public holiday calendar lives in the database so
-- the day count can be computed on the server.

CREATE TABLE leave_type (
    id               NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR2(20 CHAR) NOT NULL,
    name             VARCHAR2(80 CHAR) NOT NULL,
    annual_allowance NUMBER(4)         NOT NULL,
    active           NUMBER(1)         DEFAULT 1 NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_type PRIMARY KEY (id),
    CONSTRAINT uk_leave_type_code UNIQUE (code),
    CONSTRAINT ck_leave_type_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_leave_type_allowance CHECK (annual_allowance > 0)
);

COMMENT ON TABLE leave_type IS 'Leave category and its yearly allowance';

CREATE TABLE leave_balance (
    id            NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    employee_id   NUMBER(19)       NOT NULL,
    leave_type_id NUMBER(19)       NOT NULL,
    leave_year    NUMBER(4)        NOT NULL,
    allocated     NUMBER(4)        NOT NULL,
    used          NUMBER(4)        DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_balance PRIMARY KEY (id),
    CONSTRAINT uk_leave_balance UNIQUE (employee_id, leave_type_id, leave_year),
    CONSTRAINT ck_leave_balance_used CHECK (used >= 0 AND used <= allocated),
    CONSTRAINT fk_leave_balance_employee FOREIGN KEY (employee_id) REFERENCES employee (id),
    CONSTRAINT fk_leave_balance_type FOREIGN KEY (leave_type_id) REFERENCES leave_type (id)
);

COMMENT ON TABLE leave_balance IS 'Days granted and used per employee, type and year';
COMMENT ON COLUMN leave_balance.allocated IS 'Allowance for the year; remaining is allocated - used';

CREATE TABLE public_holiday (
    id           NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    holiday_date DATE              NOT NULL,
    name         VARCHAR2(150 CHAR) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_public_holiday PRIMARY KEY (id),
    CONSTRAINT uk_public_holiday_date UNIQUE (holiday_date)
);

COMMENT ON TABLE public_holiday IS 'University holiday calendar; excluded from the leave day count';

CREATE TABLE leave_application (
    id                       NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    employee_id              NUMBER(19)        NOT NULL,
    leave_type_id            NUMBER(19)        NOT NULL,
    start_date               DATE              NOT NULL,
    end_date                 DATE              NOT NULL,
    days                     NUMBER(4)         NOT NULL,
    reason                   VARCHAR2(1000 CHAR),
    status                   VARCHAR2(20 CHAR) NOT NULL,
    supervisor_employee_id   NUMBER(19),
    supervisor_decided_at    TIMESTAMP WITH TIME ZONE,
    decided_by_employee_id   NUMBER(19),
    decided_at               TIMESTAMP WITH TIME ZONE,
    remarks                  VARCHAR2(1000 CHAR),
    created_at               TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_application PRIMARY KEY (id),
    CONSTRAINT ck_leave_status CHECK (status IN
        ('PENDING_SUPERVISOR', 'PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_leave_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_leave_days CHECK (days > 0),
    CONSTRAINT fk_leave_employee FOREIGN KEY (employee_id) REFERENCES employee (id),
    CONSTRAINT fk_leave_type FOREIGN KEY (leave_type_id) REFERENCES leave_type (id),
    CONSTRAINT fk_leave_supervisor FOREIGN KEY (supervisor_employee_id) REFERENCES employee (id),
    CONSTRAINT fk_leave_decided_by FOREIGN KEY (decided_by_employee_id) REFERENCES employee (id)
);

COMMENT ON TABLE leave_application IS 'A leave request and its decision';
COMMENT ON COLUMN leave_application.days IS 'Working days counted from the holiday calendar';

CREATE INDEX idx_leave_employee_start ON leave_application (employee_id, start_date);
CREATE INDEX idx_leave_status ON leave_application (status);
CREATE INDEX idx_leave_supervisor ON leave_application (supervisor_employee_id, status);


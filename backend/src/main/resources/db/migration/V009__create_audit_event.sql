-- Audit trail for privileged actions (docs/SECURITY.md, "Audit review").
-- Oracle Database Free 23ai, unquoted identifiers.
--
-- Rows are only ever appended. The actor is stored as text rather than as a
-- foreign key so the trail still reads correctly if an account is later
-- renamed, disabled or removed, and no detail column ever holds a password or
-- password hash.

CREATE TABLE audit_event (
    id             NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    occurred_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    actor_username VARCHAR2(60 CHAR) NOT NULL,
    action         VARCHAR2(40 CHAR) NOT NULL,
    target_type    VARCHAR2(40 CHAR) NOT NULL,
    target_id      VARCHAR2(60 CHAR) NULL,
    detail         VARCHAR2(1000 CHAR) NULL,
    CONSTRAINT pk_audit_event PRIMARY KEY (id)
);

COMMENT ON TABLE audit_event IS 'Append-only record of privileged and authentication actions';
COMMENT ON COLUMN audit_event.actor_username IS 'Username that performed the action, or "system"';
COMMENT ON COLUMN audit_event.action IS 'Action code, for example ACCOUNT_CREATED';
COMMENT ON COLUMN audit_event.detail IS 'Human-readable summary; never contains a password or hash';

CREATE INDEX idx_audit_event_time ON audit_event (occurred_at);
CREATE INDEX idx_audit_event_actor ON audit_event (actor_username, occurred_at);

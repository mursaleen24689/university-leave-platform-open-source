-- In-app notifications (docs/REQUIREMENTS.md, "keep people informed").
-- Oracle Database Free 26ai, unquoted identifiers.
--
-- One row is one message for one account. The recipient is a real foreign key
-- rather than free text as in AUDIT_EVENT, because a message without the
-- account it belongs to is worthless: it must never be possible to write one
-- for a username that does not exist. A message is only ever created and
-- marked read; its words are never edited, so the title and body are
-- updatable=false for everything except READ_AT.

CREATE TABLE notification (
    id                NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    recipient_username VARCHAR2(60 CHAR) NOT NULL,
    kind              VARCHAR2(40 CHAR)  NOT NULL,
    title             VARCHAR2(200 CHAR) NOT NULL,
    body              VARCHAR2(1000 CHAR) NULL,
    application_id    NUMBER(19)         NULL,
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    read_at           TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT pk_notification PRIMARY KEY (id),
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_username)
        REFERENCES app_user (username) ON DELETE CASCADE,
    CONSTRAINT ck_notification_kind CHECK (LENGTH(kind) > 0)
);

COMMENT ON TABLE notification IS 'In-app messages shown by the bell in the header';
COMMENT ON COLUMN notification.recipient_username IS 'The account this message is for; nobody else can read it';
COMMENT ON COLUMN notification.kind IS 'Event code, for example REQUEST_WAITING; decides which screen a click opens';
COMMENT ON COLUMN notification.title IS 'The one line shown in the list; never contains a password';
COMMENT ON COLUMN notification.body IS 'The detail lines under the title; never contains a password or hash';
COMMENT ON COLUMN notification.application_id IS 'The leave request this message is about, if it is about one';
COMMENT ON COLUMN notification.read_at IS 'Set once when the recipient reads it; NULL means unread';

CREATE INDEX idx_notification_recipient ON notification (recipient_username, created_at);
CREATE INDEX idx_notification_unread ON notification (recipient_username, read_at);

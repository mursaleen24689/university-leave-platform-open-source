-- Oracle Database Free 23ai.
-- Unquoted identifiers fold to upper case, so the tables below are FACULTY
-- and DEPARTMENT while the Java entities use lower-case names. Do not quote
-- identifiers in either place, or the two will stop matching.
-- Character lengths use CHAR semantics so multi-byte names fit.

CREATE TABLE faculty (
    id         NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    code       VARCHAR2(16 CHAR) NOT NULL,
    name       VARCHAR2(150 CHAR) NOT NULL,
    active     NUMBER(1)         DEFAULT 1 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_faculty PRIMARY KEY (id),
    CONSTRAINT uk_faculty_code UNIQUE (code),
    CONSTRAINT ck_faculty_active CHECK (active IN (0, 1))
);

COMMENT ON TABLE faculty IS 'Top-level grouping: academic faculty or administrative wing';

CREATE TABLE department (
    id              NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    faculty_id      NUMBER(19)        NOT NULL,
    code            VARCHAR2(16 CHAR) NOT NULL,
    name            VARCHAR2(150 CHAR) NOT NULL,
    department_type VARCHAR2(20 CHAR) NOT NULL,
    active          NUMBER(1)         DEFAULT 1 NOT NULL,
    successor_id    NUMBER(19)        NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_department PRIMARY KEY (id),
    CONSTRAINT uk_department_code UNIQUE (code),
    CONSTRAINT ck_department_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_department_type CHECK (department_type IN ('ACADEMIC', 'ADMINISTRATIVE', 'SUPPORT')),
    CONSTRAINT fk_department_faculty FOREIGN KEY (faculty_id) REFERENCES faculty (id),
    CONSTRAINT fk_department_successor FOREIGN KEY (successor_id) REFERENCES department (id)
);

COMMENT ON TABLE department IS 'Department or office; codes are permanent and never reused';
COMMENT ON COLUMN department.successor_id IS 'Set when a department is merged into another one';

CREATE INDEX idx_department_faculty_active ON department (faculty_id, active);
CREATE INDEX idx_department_type_active ON department (department_type, active);

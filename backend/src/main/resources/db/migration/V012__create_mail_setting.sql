-- The mail settings the university's own IT staff fill in when they have the
-- mail server details, and the record of what was tried.
--
-- One row of settings is deliberate. A second mail server for the same platform
-- would mean deciding which message went where, and nobody has asked for that;
-- the row is read on every send, so a change takes effect without a restart.
--
-- `password_cipher` never holds a password in the clear: it is AES-GCM over the
-- key in `LEAVE_MAIL_KEY`, and no read path gives it back. An empty column means
-- "no password saved", which is how the platform starts - the screen shows a
-- blank box, not a hidden old value.
CREATE TABLE mail_setting (
    id              NUMBER(19)         DEFAULT 1 NOT NULL,
    enabled         NUMBER(1)          DEFAULT 0 NOT NULL,
    host            VARCHAR2(250 CHAR) NULL,
    port            NUMBER(5)          NULL,
    username        VARCHAR2(250 CHAR) NULL,
    password_cipher VARCHAR2(1000 CHAR) NULL,
    from_address    VARCHAR2(320 CHAR) NULL,
    use_tls         NUMBER(1)          DEFAULT 1 NOT NULL,
    mailed_events   VARCHAR2(400 CHAR) NULL,
    updated_by      VARCHAR2(60 CHAR)  NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT pk_mail_setting PRIMARY KEY (id),
    CONSTRAINT ck_mail_setting_id CHECK (id = 1),
    CONSTRAINT ck_mail_setting_port CHECK (port IS NULL OR (port > 0 AND port <= 65535)),
    CONSTRAINT ck_mail_setting_flag CHECK (enabled IN (0, 1) AND use_tls IN (0, 1)));

-- Every send attempt, one row each, so the person who typed the settings can see
-- whether the platform ever reached the mail server and what it said back. This
-- is a log, not a queue: a failed message is not retried, and the in-app message
-- was already stored before the attempt, so nothing is lost either way.
CREATE TABLE mail_log (
    id         NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    attempted_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    recipient  VARCHAR2(320 CHAR)  NULL,
    subject    VARCHAR2(200 CHAR)  NULL,
    outcome    VARCHAR2(20 CHAR)   NOT NULL,
    detail     VARCHAR2(1000 CHAR) NULL,
    CONSTRAINT pk_mail_log PRIMARY KEY (id),
    CONSTRAINT ck_mail_log_outcome CHECK (outcome IN ('SENT', 'FAILED', 'SKIPPED')));

CREATE INDEX idx_mail_log_recent ON mail_log (attempted_at DESC);


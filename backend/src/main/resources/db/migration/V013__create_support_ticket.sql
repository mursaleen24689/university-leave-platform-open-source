-- Help-desk tickets (docs/REQUIREMENTS.md, "a staff member can ask for help").
-- Oracle Database Free 26ai, unquoted identifiers.
--
-- One row is one open question from one member of staff. The person who opened
-- it is a foreign key to EMPLOYEE, the same way a leave request is, because a
-- ticket is about a person and their record and has to outlive the sign-in
-- account they used to write it - unlike NOTIFICATION, which is worthless
-- without a reader. DEPARTMENT_ID is the department at the time the ticket was
-- opened and is never re-derived, so a transfer does not move an old ticket.
--
-- The conversation is the second table and it is append-only: no update or
-- delete path exists in the platform, so a reply cannot be quietly reworded
-- after the fact. The thread, not the ticket row, is what a person reads.
--
-- The status is kept as one column with a CHECK list rather than a status
-- history table because a help desk has one question - does somebody owe an
-- answer - and CLOSED_AT says when it stopped. FROM_DESK marks which side wrote
-- a line, so the same list reads correctly for both the staff member and the
-- desk; it is derived from the account's role when the line is written and is
-- not something the caller can claim.

CREATE TABLE support_ticket (
    id                    NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    reference             VARCHAR2(20 CHAR)  NOT NULL,
    opened_by_employee_id NUMBER(19)         NOT NULL,
    department_id         NUMBER(19)         NOT NULL,
    category              VARCHAR2(30 CHAR)  NOT NULL,
    subject               VARCHAR2(200 CHAR) NOT NULL,
    status                VARCHAR2(20 CHAR)  DEFAULT 'OPEN' NOT NULL,
    assignee_employee_id  NUMBER(19)         NULL,
    created_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    closed_at             TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT pk_support_ticket PRIMARY KEY (id),
    CONSTRAINT uq_ticket_reference UNIQUE (reference),
    CONSTRAINT fk_ticket_employee FOREIGN KEY (opened_by_employee_id)
        REFERENCES employee (id),
    CONSTRAINT fk_ticket_department FOREIGN KEY (department_id)
        REFERENCES department (id),
    CONSTRAINT fk_ticket_assignee FOREIGN KEY (assignee_employee_id)
        REFERENCES employee (id),
    CONSTRAINT ck_ticket_category CHECK
        (category IN ('LEAVE_RECORD', 'ACCOUNT_ACCESS', 'SYSTEM_PROBLEM', 'OTHER')),
    CONSTRAINT ck_ticket_status CHECK
        (status IN ('OPEN', 'IN_PROGRESS', 'ANSWERED', 'CLOSED')),
    CONSTRAINT ck_ticket_closed CHECK
        ((status = 'CLOSED' AND closed_at IS NOT NULL)
         OR (status <> 'CLOSED' AND closed_at IS NULL)),
    CONSTRAINT ck_ticket_subject CHECK (LENGTH(TRIM(subject)) > 0)
);

COMMENT ON TABLE support_ticket IS 'One help-desk question from one member of staff';
COMMENT ON COLUMN support_ticket.reference IS 'The short number the staff member and the desk quote to each other, for example HD-000042';
COMMENT ON COLUMN support_ticket.department_id IS 'Department at the time the ticket was opened; a later transfer does not change it';
COMMENT ON COLUMN support_ticket.category IS 'What kind of help: LEAVE_RECORD, ACCOUNT_ACCESS, SYSTEM_PROBLEM or OTHER';
COMMENT ON COLUMN support_ticket.status IS 'OPEN or IN_PROGRESS wait for the desk, ANSWERED waits for the staff member, CLOSED is finished';
COMMENT ON COLUMN support_ticket.assignee_employee_id IS 'The staff member the desk gave it to, if anybody; the role check is in the application, not here';
COMMENT ON COLUMN support_ticket.closed_at IS 'Set when the ticket was closed and cleared when it is reopened; NULL while it is open';

CREATE INDEX idx_ticket_opened_by ON support_ticket (opened_by_employee_id, created_at);
CREATE INDEX idx_ticket_status ON support_ticket (status, created_at);

CREATE TABLE ticket_message (
    id                 NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    ticket_id          NUMBER(19)          NOT NULL,
    author_employee_id NUMBER(19)          NOT NULL,
    from_desk          NUMBER(1)           DEFAULT 0 NOT NULL,
    body               VARCHAR2(2000 CHAR) NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ticket_message PRIMARY KEY (id),
    CONSTRAINT fk_ticket_message_ticket FOREIGN KEY (ticket_id)
        REFERENCES support_ticket (id),
    CONSTRAINT fk_ticket_message_author FOREIGN KEY (author_employee_id)
        REFERENCES employee (id),
    CONSTRAINT ck_ticket_message_desk CHECK (from_desk IN (0, 1)),
    CONSTRAINT ck_ticket_message_body CHECK (LENGTH(TRIM(body)) > 0)
);

COMMENT ON TABLE ticket_message IS 'The words of a ticket, in order, written once and never changed';
COMMENT ON COLUMN ticket_message.from_desk IS '1 when a central administrator wrote the line, 0 when the staff member who opened the ticket did';
COMMENT ON COLUMN ticket_message.body IS 'What was said; never contains a password or a security code, which the screen asks for and the writer must not paste';

CREATE INDEX idx_ticket_message_ticket ON ticket_message (ticket_id, created_at);

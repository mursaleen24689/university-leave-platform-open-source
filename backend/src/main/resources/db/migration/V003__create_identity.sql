-- Identity and access (Phase 2, epic 1).
-- Oracle Database Free 23ai. Unquoted identifiers fold to upper case.
-- USER and ROLE are keywords, hence the APP_ prefix on both tables.

CREATE TABLE employee (
    id                    NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    employee_no           VARCHAR2(30 CHAR) NOT NULL,
    full_name             VARCHAR2(150 CHAR) NOT NULL,
    email                 VARCHAR2(150 CHAR) NOT NULL,
    designation           VARCHAR2(100 CHAR) NOT NULL,
    department_id         NUMBER(19)        NOT NULL,
    supervisor_employee_id NUMBER(19)       NULL,
    active                NUMBER(1)         DEFAULT 1 NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_employee PRIMARY KEY (id),
    CONSTRAINT uk_employee_no UNIQUE (employee_no),
    CONSTRAINT uk_employee_email UNIQUE (email),
    CONSTRAINT ck_employee_active CHECK (active IN (0, 1)),
    CONSTRAINT fk_employee_department FOREIGN KEY (department_id) REFERENCES department (id),
    CONSTRAINT fk_employee_supervisor FOREIGN KEY (supervisor_employee_id) REFERENCES employee (id)
);

COMMENT ON TABLE employee IS 'University employee; employee_no is the university-wide key';
COMMENT ON COLUMN employee.supervisor_employee_id IS 'Optional recommending officer; HOD comes from the department';

CREATE INDEX idx_employee_department_active ON employee (department_id, active);

CREATE TABLE app_role (
    id   NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR2(30 CHAR) NOT NULL,
    name VARCHAR2(80 CHAR)  NOT NULL,
    CONSTRAINT pk_app_role PRIMARY KEY (id),
    CONSTRAINT uk_app_role_code UNIQUE (code)
);

COMMENT ON TABLE app_role IS 'Fixed permission set; a user may hold several roles';

CREATE TABLE app_user (
    id                   NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
    employee_id          NUMBER(19)        NOT NULL,
    username             VARCHAR2(60 CHAR) NOT NULL,
    password_hash        VARCHAR2(100 CHAR) NOT NULL,
    enabled              NUMBER(1)         DEFAULT 1 NOT NULL,
    must_change_password NUMBER(1)         DEFAULT 1 NOT NULL,
    failed_attempts      NUMBER(3)         DEFAULT 0 NOT NULL,
    locked_until         TIMESTAMP WITH TIME ZONE NULL,
    last_login_at        TIMESTAMP WITH TIME ZONE NULL,
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT uk_app_user_employee UNIQUE (employee_id),
    CONSTRAINT ck_app_user_enabled CHECK (enabled IN (0, 1)),
    CONSTRAINT ck_app_user_must_change CHECK (must_change_password IN (0, 1)),
    CONSTRAINT ck_app_user_failed_attempts CHECK (failed_attempts >= 0),
    CONSTRAINT fk_app_user_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

COMMENT ON TABLE app_user IS 'Login account; one per employee, password stored as a BCrypt hash';
COMMENT ON COLUMN app_user.locked_until IS 'Temporary lock after repeated failures; NULL means not locked';

CREATE TABLE user_role (
    user_id NUMBER(19) NOT NULL,
    role_id NUMBER(19) NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES app_role (id)
);

CREATE INDEX idx_user_role_role ON user_role (role_id);

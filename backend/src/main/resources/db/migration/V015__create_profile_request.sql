-- Profile-change requests (docs/REQUIREMENTS.md, "a member of staff can ask for a
-- correction to their own record").
-- Oracle Database Free 26ai, unquoted identifiers.
--
-- One row is one set of corrections one person proposes for their own staff
-- record. The office approves or refuses the row as a whole, so a person with a
-- wrong name and a wrong phone does not have to wait for two answers, and the
-- audit trail has one entry per decision rather than one per column.
--
-- WHY CHANGED_FIELDS EXISTS. Oracle stores an empty string as NULL, so a blank
-- column cannot tell "not proposed" apart from "proposed as empty". The list is
-- therefore the authoritative statement of what this request changes, and only
-- the columns it names are ever written to the employee record. A column that is
-- not named is left exactly as it stands, whatever it contains - that is the
-- rule, and the list is how the row keeps it. the earlier application lost staff numbers this way
-- when an approval copied every field it was not asked to touch.
--
-- Because only named columns are applied, and because clearing a staff number or
-- an e-mail is the office's decision and not a correction a person can propose at
-- a keyboard, the CHECK below insists that every named field carries a value. A
-- request cannot therefore say "remove my phone number"; the help desk is the way
-- to ask for that, and the employee editor on the administration screen is the
-- way to do it.
--
-- The name, staff number, designation, e-mail and phone are the five a person
-- knows their own way round. A department transfer or a change of reporting line
-- is deliberately absent: it decides whose leave requests the person sends and
-- whose approvals reach them, so it is made by the office, in the organisation
-- screen, where the department code is chosen rather than typed.
--
-- No "current value" columns: the office reads the live record beside the
-- proposed one when it decides, so a correction made in the meantime cannot be
-- approved against a snapshot that no longer exists.

CREATE TABLE profile_request (
    id                     NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    reference              VARCHAR2(20 CHAR)   NOT NULL,
    employee_id            NUMBER(19)          NOT NULL,
    changed_fields         VARCHAR2(200 CHAR)  NOT NULL,
    full_name_proposed     VARCHAR2(150 CHAR)  NULL,
    employee_no_proposed   VARCHAR2(30 CHAR)   NULL,
    designation_proposed   VARCHAR2(100 CHAR)  NULL,
    email_proposed         VARCHAR2(150 CHAR)  NULL,
    phone_proposed         VARCHAR2(40 CHAR)   NULL,
    reason                 VARCHAR2(1000 CHAR) NULL,
    status                 VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    decided_by_employee_id NUMBER(19)          NULL,
    decision_note          VARCHAR2(1000 CHAR) NULL,
    created_at             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    decided_at             TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT pk_profile_request PRIMARY KEY (id),
    CONSTRAINT uq_profile_reference UNIQUE (reference),
    CONSTRAINT fk_profile_employee FOREIGN KEY (employee_id)
        REFERENCES employee (id),
    CONSTRAINT fk_profile_decided_by FOREIGN KEY (decided_by_employee_id)
        REFERENCES employee (id),
    CONSTRAINT ck_profile_status CHECK
        (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_profile_named CHECK
        ((changed_fields NOT LIKE '%FULL_NAME%'   OR full_name_proposed   IS NOT NULL)
         AND (changed_fields NOT LIKE '%EMPLOYEE_NO%' OR employee_no_proposed IS NOT NULL)
         AND (changed_fields NOT LIKE '%DESIGNATION%' OR designation_proposed IS NOT NULL)
         AND (changed_fields NOT LIKE '%EMAIL%'    OR email_proposed      IS NOT NULL)
         AND (changed_fields NOT LIKE '%PHONE%'    OR phone_proposed      IS NOT NULL)),
    CONSTRAINT ck_profile_changed CHECK (LENGTH(TRIM(changed_fields)) > 0),
    CONSTRAINT ck_profile_decided CHECK
        ((status = 'PENDING'
          AND decided_at IS NULL AND decided_by_employee_id IS NULL)
         OR (status <> 'PENDING'
             AND decided_at IS NOT NULL AND decided_by_employee_id IS NOT NULL))
);

COMMENT ON TABLE profile_request IS 'Corrections one member of staff proposes for their own record, decided by the office';
COMMENT ON COLUMN profile_request.reference IS 'The number both sides quote, for example PR-000042; written by profile_reference_bi';
COMMENT ON COLUMN profile_request.employee_id IS 'Whose record this is and who asked - a person proposes changes to their own record only';
COMMENT ON COLUMN profile_request.changed_fields IS 'Comma-separated names of the fields this request changes; the only columns applied to the employee record';
COMMENT ON COLUMN profile_request.full_name_proposed IS 'The name asked for; ignored unless changed_fields names FULL_NAME';
COMMENT ON COLUMN profile_request.employee_no_proposed IS 'The staff number asked for; ignored unless changed_fields names EMPLOYEE_NO';
COMMENT ON COLUMN profile_request.designation_proposed IS 'The designation asked for; ignored unless changed_fields names DESIGNATION';
COMMENT ON COLUMN profile_request.email_proposed IS 'The e-mail asked for, already lower-cased; ignored unless changed_fields names EMAIL';
COMMENT ON COLUMN profile_request.phone_proposed IS 'The phone number asked for; ignored unless changed_fields names PHONE';
COMMENT ON COLUMN profile_request.reason IS 'Why the person wants the change; written by them and read by the office';
COMMENT ON COLUMN profile_request.status IS 'PENDING waits for the office; APPROVED and REJECTED are its answer; CANCELLED was withdrawn by the person who asked';
COMMENT ON COLUMN profile_request.decided_by_employee_id IS 'The office member who approved or refused, or the person who withdrew it; NULL while PENDING';
COMMENT ON COLUMN profile_request.decision_note IS 'What the office said about its decision; required when refusing, so a refusal can be acted on';
COMMENT ON COLUMN profile_request.decided_at IS 'When the request stopped being pending; NULL while PENDING';

CREATE INDEX idx_profile_employee ON profile_request (employee_id, created_at);
CREATE INDEX idx_profile_status ON profile_request (status, created_at);

-- A second pending request from the same person would put two answers to the
-- same question in front of the office. The expression is NULL for every row
-- that has been decided, and Oracle keeps no entries for an all-NULL key in a
-- single-column index, so the restriction is only on the pending ones. The
-- application gives the readable message; this index is what stops two requests
-- submitted in the same second from both landing in the queue.
CREATE UNIQUE INDEX uq_profile_one_pending
    ON profile_request (CASE WHEN status = 'PENDING' THEN employee_id END);

-- The number is written by the database for the reason recorded for help-desk
-- tickets in docs/DECISIONS.md (ADR-016): an id-derived reference cannot be
-- carried by the INSERT statement itself, and Oracle assigns the identity value
-- before a BEFORE INSERT row trigger runs.
CREATE OR REPLACE TRIGGER profile_reference_bi
BEFORE INSERT ON profile_request
FOR EACH ROW
BEGIN
    :NEW.reference := 'PR-' || LPAD(TO_CHAR(:NEW.id), 6, '0');
END;
/

COMMENT ON COLUMN profile_request.reference IS 'Written by profile_reference_bi from the id, in the form PR-000042; never typed and never edited';
